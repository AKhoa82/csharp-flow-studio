import { createFileRoute } from "@tanstack/react-router";
import { useState } from "react";
import { Check, CheckCircle2, Pencil, RefreshCw, X } from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { Tabs, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { AIBadge, CodeBlock, PageHeader, SectionCard, StatusBadge } from "@/components/primitives";
import { lessonContent, pendingReview, sampleCode } from "@/lib/mock-data";
import { cn } from "@/lib/utils";

export const Route = createFileRoute("/admin/review/")({
  head: () => ({
    meta: [
      { title: "AI Content Review — CSharpHub Studio" },
      { name: "description", content: "Moderate AI-generated C# lessons and questions before they reach students." },
      { property: "og:title", content: "AI Content Review — CSharpHub Studio" },
      { property: "og:description", content: "Moderate AI-generated C# lessons and questions before they reach students." },
    ],
  }),
  component: ReviewQueue,
});

function ReviewQueue() {
  const [selected, setSelected] = useState(pendingReview[0]!.id);
  const [reason, setReason] = useState("");
  const item = pendingReview.find((p) => p.id === selected)!;

  return (
    <div className="space-y-6">
      <PageHeader title="AI Content Review" description="Nothing generated by AI reaches students without a human decision." />

      <Tabs defaultValue="pending">
        <TabsList>
          {["all", "lessons", "questions", "pending", "approved", "rejected"].map((t) => (
            <TabsTrigger key={t} value={t} className="capitalize">{t}</TabsTrigger>
          ))}
        </TabsList>
      </Tabs>

      <div className="grid gap-4 lg:grid-cols-[320px_minmax(0,1fr)]">
        <SectionCard title="Queue" description={`${pendingReview.length} items pending`} bodyClassName="p-2">
          <ul className="space-y-1">
            {pendingReview.map((p) => (
              <li key={p.id}>
                <button
                  onClick={() => setSelected(p.id)}
                  className={cn("w-full rounded-xl p-3 text-left transition-colors", selected === p.id ? "bg-primary-soft" : "hover:bg-muted")}
                >
                  <div className="flex items-center gap-2">
                    <AIBadge label="AI" />
                    <span className="text-xs text-muted-foreground">{p.kind}</span>
                  </div>
                  <p className="mt-1.5 truncate text-sm font-semibold">{p.title}</p>
                  <p className="truncate text-xs text-muted-foreground">{p.course} · {p.time}</p>
                </button>
              </li>
            ))}
          </ul>
        </SectionCard>

        <div className="grid gap-4 xl:grid-cols-[minmax(0,1fr)_300px]">
          <SectionCard
            title={item.title}
            description={`${item.course} · generated ${item.time} by ${item.by}`}
            bodyClassName="space-y-4 p-5"
            action={<StatusBadge status="review" />}
          >
            <h2 className="text-lg font-bold">{lessonContent.title}</h2>
            <p className="text-sm leading-relaxed text-muted-foreground">{lessonContent.intro}</p>
            <CodeBlock code={sampleCode} filename="Student.cs" />
            <div className="rounded-xl border-l-4 border-primary bg-primary-soft p-4 text-sm">{lessonContent.callout}</div>
          </SectionCard>

          <div className="space-y-4">
            <SectionCard title="Review decision" bodyClassName="space-y-3 p-5">
              <Button className="w-full" onClick={() => toast.success("Approved", { description: item.title })}>
                <Check className="h-4 w-4" /> Approve
              </Button>
              <Button variant="outline" className="w-full" onClick={() => toast("Opening editor")}><Pencil className="h-4 w-4" /> Edit</Button>
              <Button variant="outline" className="w-full" onClick={() => toast("Regenerating…")}><RefreshCw className="h-4 w-4" /> Regenerate</Button>
              <div className="space-y-1.5 pt-2">
                <p className="text-xs font-semibold text-muted-foreground">Rejection reason (required)</p>
                <Textarea rows={3} value={reason} onChange={(e) => setReason(e.target.value)} placeholder="Explain what needs to change…" />
                <Button
                  variant="outline"
                  className="w-full border-destructive/40 text-destructive hover:bg-danger-soft"
                  onClick={() => reason.trim() ? toast.error("Rejected", { description: reason }) : toast.error("A reason is required to reject")}
                >
                  <X className="h-4 w-4" /> Reject
                </Button>
              </div>
            </SectionCard>

            <SectionCard title="Audit timeline" bodyClassName="p-5">
              <ol className="relative space-y-5 border-l border-border pl-5">
                {[
                  ["Generated by AI", item.time],
                  ["Moved to draft", item.time],
                  ["Queued for review", item.time],
                ].map(([a, t]) => (
                  <li key={a} className="relative">
                    <span className="absolute -left-[1.65rem] grid h-5 w-5 place-items-center rounded-full border-2 border-background bg-secondary text-muted-foreground">
                      <CheckCircle2 className="h-2.5 w-2.5" />
                    </span>
                    <p className="text-sm font-medium">{a}</p>
                    <p className="text-xs text-muted-foreground">{t}</p>
                  </li>
                ))}
              </ol>
            </SectionCard>
          </div>
        </div>
      </div>
    </div>
  );
}
